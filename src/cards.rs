#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn presets_are_complete_and_references_are_consistent() {
        let catalog = cards();
        assert_eq!(catalog.len(), 308);
        for (index, card) in catalog.iter().enumerate() {
            assert_eq!(index, card.id);
            assert!(!card.official_id.is_empty());
            assert!(
                !card.official_text.is_empty() || matches!(card.id, 69..=73),
                "Only explicitly reviewed vanilla units may have empty rules text."
            );
            assert!(!card.official_text.contains(":rb_"));
            assert!(card.art_url.starts_with("https://cmsassets.rgpub.io/"));
        }
        for deck in presets() {
            assert!(!deck.legend_text.is_empty());
            assert!(!deck.learning_notes.is_empty());
            assert_eq!(
                deck.cards.iter().map(|(_, n)| *n as usize).sum::<usize>(),
                40
            );
            assert!(
                deck.cards
                    .iter()
                    .any(|(id, count)| *id == deck.chosen_champion && *count >= 1)
            );
            let mut ids = std::collections::HashSet::new();
            for (id, count) in deck.cards {
                assert!(id < catalog.len());
                assert!((1..=3).contains(&count));
                assert!(ids.insert(id), "duplicate card group");
                assert!(deck.domains.contains(&catalog[id].domain));
            }
            assert_eq!(catalog[deck.chosen_champion].kind, CardKind::Unit);
        }
    }
}
