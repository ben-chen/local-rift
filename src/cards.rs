//! Official card facts and sourced tournament-list presets for offline play.
//! Card behavior is mapped in rules.rs and executed by the game modules.
//! Source provenance and implementation limits are documented separately.

pub type CardId = usize;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Domain {
    Fury,
    Calm,
    Mind,
    Body,
    Chaos,
    Order,
}
impl Domain {
    pub const fn name(self) -> &'static str {
        match self {
            Self::Fury => "Fury",
            Self::Calm => "Calm",
            Self::Mind => "Mind",
            Self::Body => "Body",
            Self::Chaos => "Chaos",
            Self::Order => "Order",
        }
    }
    pub const fn color(self) -> [u8; 3] {
        match self {
            Self::Fury => [239, 108, 111],
            Self::Calm => [105, 226, 203],
            Self::Mind => [111, 177, 255],
            Self::Body => [224, 166, 103],
            Self::Chaos => [179, 144, 255],
            Self::Order => [235, 214, 132],
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CardKind {
    Unit,
    Spell,
    Gear,
}
impl CardKind {
    pub const fn name(self) -> &'static str {
        match self {
            Self::Unit => "Unit",
            Self::Spell => "Spell",
            Self::Gear => "Gear",
        }
    }
}

#[derive(Clone, Copy, Debug)]
pub struct CardDef {
    pub id: CardId,
    /// Stable official printing identifier, independent of the runtime index.
    pub official_id: &'static str,
    pub name: &'static str,
    pub cost: u8,
    pub power_cost: u8,
    pub might: u8,
    pub domain: Domain,
    /// All printed domains; generic colored power may use any listed domain.
    pub domains: &'static [Domain],
    pub kind: CardKind,
    /// Official gallery rules text; icons expanded to readable resource names.
    pub official_text: &'static str,
    pub keywords: &'static [&'static str],
    /// Exact official creature, faction and champion tags; no inferred tags.
    pub tags: &'static [&'static str],
    pub art_url: &'static str,
}

#[derive(Clone, Debug)]
pub struct DeckPreset {
    /// Stable legend registry ID; independent of the preset list index.
    pub legend_id: usize,
    pub name: &'static str,
    pub legend_name: &'static str,
    pub legend_text: &'static str,
    /// Strategy notes inferred from the official card and legend abilities.
    pub learning_notes: &'static str,
    pub champion: &'static str,
    pub domains: [Domain; 2],
    pub rune_counts: [u8; 2],
    pub strategy: &'static str,
    pub difficulty: &'static str,
    /// Forty cards, including one copy removed into the chosen-champion zone.
    pub cards: Vec<(CardId, u8)>,
    pub source_url: &'static str,
    pub accent: [u8; 3],
    pub chosen_champion: CardId,
}

